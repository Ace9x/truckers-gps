// Before/after phone shots of the driving view, the live chip, and a note.
import { chromium, devices } from 'playwright';
import fs from 'node:fs';
const BASE = process.env.BASE || 'http://localhost:8765/';
const TAG = process.env.TAG || 'after';
const OUT = process.env.OUT || '/opt/cursor/artifacts';
fs.mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ ...devices['iPhone 13'], viewport: { width: 390, height: 844 }, permissions: ['geolocation'], geolocation: { latitude: 40.7282, longitude: -73.7949 } });
await ctx.addInitScript(() => { localStorage.setItem('tn_locWhySeen', '1'); localStorage.setItem('tn_tourDone', 'true'); localStorage.setItem('tn_lang', '"en"'); localStorage.setItem('tn_truckSetDone', '1'); localStorage.setItem('rr_area_asked', '1'); localStorage.setItem('tn_greeted', 'true'); localStorage.setItem('rr_whatsnew_seen', '3.33.0'); });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push(e.message));
p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await p.goto(BASE, { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => window.TruckNav?.map, null, { timeout: 30000 });
await p.waitForTimeout(1200);
if (await p.$('#lfGo')) await p.click('#lfGo');
if (await p.$('#tSkip')) await p.click('#tSkip');
await p.waitForTimeout(800);
await p.evaluate(() => { const S = window.TruckNav; S.pos = { lat: 40.7282, lon: -73.7949, speed: 0, heading: 250, acc: 8, t: Date.now() }; S.onFix?.(S.pos); document.querySelectorAll('.panel').forEach(x => x.classList.add('hidden')); });
await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/${TAG}_map.png` });
await p.evaluate(() => { const t = document.querySelector('#toast'); if (window.TruckNav.toast) window.TruckNav.toast('Route saved on this phone'); else { t.textContent = 'Route saved on this phone'; t.classList.remove('hidden'); } });
await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/${TAG}_note.png` });
await p.evaluate(() => document.querySelector('#toast')?.classList.add('hidden'));
const ready = await p.evaluate(async () => { const S = window.TruckNav; S.pos = { lat: 40.7282, lon: -73.7949, speed: 0, heading: 250, acc: 8, t: Date.now() }; S.stops = []; S.setDest({ lon: -73.8648, lat: 40.759, name: 'Flushing, NY' }); for (let i = 0; i < 40 && !S.route; i++) await new Promise(r => setTimeout(r, 500)); if (!S.route) return false; document.querySelectorAll('.panel').forEach(x => x.classList.add('hidden')); S.startNav(); S.onFix({ lat: 40.7282, lon: -73.7949, speed: 12, heading: 250, acc: 8, t: Date.now() }); const lock = document.querySelector('#mtLock'); if (lock) lock.hidden = true; return true; });
console.log(TAG, 'route', ready);
await p.waitForTimeout(1800);
await p.evaluate(() => { const lock = document.querySelector('#mtLock'); if (lock) lock.hidden = true; document.querySelector('#wnPop')?.remove(); return new Promise(res => { const m = window.TruckNav.map; if (m.loaded()) m.once('idle', res); else res(); setTimeout(res, 2500); }); });
await p.screenshot({ path: `${OUT}/${TAG}_drive.png` });
await p.evaluate(() => document.querySelector('#liveChip')?.click());
await p.waitForTimeout(400);
if (await p.$('#liveDetail:not([hidden])')) await p.screenshot({ path: `${OUT}/${TAG}_live.png` });
console.log(TAG, 'errs', errs.filter(e => !/relay|damus|nostr|tile|openfreemap/i.test(e)).slice(0, 8));
await browser.close();
if (!ready) process.exit(1);
